/* RAIZ.PG.WINDOW/0/T. Exhaustive committed original-call census.
   INICIOUTC/FIMUTC are the original START/REPORT instants, without padding.
   Both closed windows include 120 seconds on each side; no supplier/document
   filter is allowed. A global TICKET match is included regardless of company.
   All FLAN children of candidate movements are included, including orphans
   created inside the windows. TOP is accompanied by untruncated totals. */
WITH P AS (
 SELECT CAST(:CODCOLIGADA AS INT) COL,CAST(:TICKET AS VARCHAR(30)) TICKET,
 CONVERT(DATETIME2(3),:INICIOUTC,126) START_UTC,CONVERT(DATETIME2(3),:FIMUTC,126) END_UTC
), W AS (
 SELECT P.*,DATEADD(SECOND,-120,START_UTC) UTC_START,DATEADD(SECOND,120,END_UTC) UTC_END,
 DATEADD(SECOND,-120,DATEADD(HOUR,-3,START_UTC)) LOCAL_START,
 DATEADD(SECOND,120,DATEADD(HOUR,-3,END_UTC)) LOCAL_END FROM P
), M AS (
 SELECT CAST('MOV' AS VARCHAR(8)) ROW_KIND,T.CODCOLIGADA,T.CODFILIAL,T.IDMOV,CAST(NULL AS INT) IDLAN,
 T.CODCOLCFO,T.CODCFO,T.CODTMV,T.NUMEROMOV DOCUMENTO,T.SERIE,T.CODTDO,T.DATAEMISSAO,T.DATASAIDA,
 CAST(NULL AS DATETIME) DATAVENCIMENTO,T.VALORBRUTO,T.VALORLIQUIDO,T.VALORLIQUIDO VALOR,
 CAST(T.STATUS AS VARCHAR(10)) STATUS,CAST(NULL AS NUMERIC(18,4)) VALORBAIXADO,
 CAST(NULL AS INT) BAIXAPENDENTE,CAST(NULL AS INT) IDBOLETO,CAST(NULL AS INT) BOLETO_COUNT,
 CAST(NULL AS INT) IDPGTO,CAST(NULL AS INT) CODCOLPGTO,T.RECCREATEDON,T.RECMODIFIEDON,H.TICKET,
 CAST(0 AS INT) ORFAO,H.RECCREATEDON COMPLEMENT_CREATED,H.RECMODIFIEDON COMPLEMENT_MODIFIED
 FROM TMOV T WITH(READCOMMITTEDLOCK) CROSS JOIN W
 LEFT JOIN TMOVCOMPL H WITH(READCOMMITTEDLOCK) ON H.CODCOLIGADA=T.CODCOLIGADA AND H.IDMOV=T.IDMOV
 WHERE H.TICKET=W.TICKET OR (T.CODCOLIGADA=W.COL AND
 ((T.RECCREATEDON>=W.UTC_START AND T.RECCREATEDON<=W.UTC_END) OR
  (T.RECCREATEDON>=W.LOCAL_START AND T.RECCREATEDON<=W.LOCAL_END)))
), F AS (
 SELECT CAST('LAN' AS VARCHAR(8)) ROW_KIND,F.CODCOLIGADA,F.CODFILIAL,F.IDMOV,F.IDLAN,
 F.CODCOLCFO,F.CODCFO,T.CODTMV,F.NUMERODOCUMENTO DOCUMENTO,T.SERIE,T.CODTDO,F.DATAEMISSAO,T.DATASAIDA,
 F.DATAVENCIMENTO,T.VALORBRUTO,T.VALORLIQUIDO,F.VALORORIGINAL VALOR,
 CAST(F.STATUSLAN AS VARCHAR(10)) STATUS,F.VALORBAIXADO,F.BAIXAPENDENTE,F.IDBOLETO,
 (SELECT COUNT(*) FROM FLANBOLETO B WITH(READCOMMITTEDLOCK) WHERE B.CODCOLIGADA=F.CODCOLIGADA AND B.IDLAN=F.IDLAN) BOLETO_COUNT,
 F.IDPGTO,F.CODCOLPGTO,F.RECCREATEDON,F.RECMODIFIEDON,H.TICKET,
 CASE WHEN F.IDMOV IS NULL OR T.IDMOV IS NULL THEN 1 ELSE 0 END ORFAO,
 H.RECCREATEDON COMPLEMENT_CREATED,H.RECMODIFIEDON COMPLEMENT_MODIFIED
 FROM FLAN F WITH(READCOMMITTEDLOCK) CROSS JOIN W
 LEFT JOIN TMOV T WITH(READCOMMITTEDLOCK) ON T.CODCOLIGADA=F.CODCOLIGADA AND T.IDMOV=F.IDMOV
 LEFT JOIN TMOVCOMPL H WITH(READCOMMITTEDLOCK) ON H.CODCOLIGADA=F.CODCOLIGADA AND H.IDMOV=F.IDMOV
 WHERE H.TICKET=W.TICKET OR EXISTS(SELECT 1 FROM M WHERE M.CODCOLIGADA=F.CODCOLIGADA AND M.IDMOV=F.IDMOV)
 OR (F.CODCOLIGADA=W.COL AND
 ((F.RECCREATEDON>=W.UTC_START AND F.RECCREATEDON<=W.UTC_END) OR
  (F.RECCREATEDON>=W.LOCAL_START AND F.RECCREATEDON<=W.LOCAL_END)))
), R AS (SELECT * FROM M UNION ALL SELECT * FROM F)
SELECT TOP(1001) CAST(1 AS INT) WINDOW_VERSION,W.COL REQUEST_COMPANY,W.TICKET REQUEST_TICKET,
 W.START_UTC REQUEST_START_UTC,W.END_UTC REQUEST_END_UTC,
 W.UTC_START WINDOW_START_UTC,W.UTC_END WINDOW_END_UTC,
 W.LOCAL_START WINDOW_START_LOCAL,W.LOCAL_END WINDOW_END_LOCAL,
 (SELECT COUNT(*) FROM M) TOTAL_MOVEMENTS,(SELECT COUNT(*) FROM F) TOTAL_LAUNCHES,R.*
FROM W LEFT JOIN R ON 1=1
ORDER BY R.ROW_KIND,R.CODCOLIGADA,R.IDMOV,R.IDLAN
