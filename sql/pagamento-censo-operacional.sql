/* Read-only committed census for individually approved legacy reconciliation. */
WITH P AS (
 SELECT CAST(:CODCOLIGADA AS INT) COL,CAST(:CODCOLCFO AS INT) CFOCOL,
 CAST(:CODCFO AS VARCHAR(25)) CFO,CAST(:TICKET AS VARCHAR(30)) TICKET,
 CAST(:NUMERO AS VARCHAR(35)) NUMERO,CONVERT(DATE,:EMISSAO,126) EMISSAO,
 CONVERT(DATETIME,:INICIO,126) INICIO,CONVERT(DATETIME,:FIM,126) FIM
), M AS (
 SELECT CAST('MOV' AS VARCHAR(8)) ROW_KIND,T.CODCOLIGADA,T.CODFILIAL,T.IDMOV,CAST(NULL AS INT) IDLAN,
 T.CODCOLCFO,T.CODCFO,T.CODTMV,T.NUMEROMOV DOCUMENTO,T.SERIE,T.CODTDO,T.DATAEMISSAO,T.DATASAIDA,
 CAST(NULL AS DATETIME) DATAVENCIMENTO,T.VALORBRUTO,T.VALORLIQUIDO,T.VALORLIQUIDO VALOR,
 CAST(T.STATUS AS VARCHAR(10)) STATUS,CAST(NULL AS NUMERIC(18,4)) VALORBAIXADO,
 CAST(NULL AS INT) BAIXAPENDENTE,CAST(NULL AS INT) IDBOLETO,CAST(NULL AS INT) BOLETO_COUNT,
 CAST(NULL AS INT) IDPGTO,CAST(NULL AS INT) CODCOLPGTO,T.RECCREATEDON,T.RECMODIFIEDON,H.TICKET,
 CAST(0 AS INT) ORFAO
 FROM TMOV T WITH(READCOMMITTEDLOCK) CROSS JOIN P
 LEFT JOIN TMOVCOMPL H WITH(READCOMMITTEDLOCK) ON H.CODCOLIGADA=T.CODCOLIGADA AND H.IDMOV=T.IDMOV
 WHERE T.CODCOLIGADA=P.COL AND (H.TICKET=P.TICKET OR
 (T.CODCOLCFO=P.CFOCOL AND T.CODCFO=P.CFO AND
 (LTRIM(RTRIM(T.NUMEROMOV))=P.NUMERO OR TRY_CONVERT(BIGINT,T.NUMEROMOV)=TRY_CONVERT(BIGINT,P.NUMERO)
 OR (T.DATAEMISSAO>=P.EMISSAO AND T.DATAEMISSAO<DATEADD(DAY,1,P.EMISSAO))
 OR (T.RECCREATEDON>=P.INICIO AND T.RECCREATEDON<P.FIM))))
), F AS (
 SELECT CAST('LAN' AS VARCHAR(8)) ROW_KIND,F.CODCOLIGADA,F.CODFILIAL,F.IDMOV,F.IDLAN,
 F.CODCOLCFO,F.CODCFO,T.CODTMV,F.NUMERODOCUMENTO DOCUMENTO,T.SERIE,T.CODTDO,F.DATAEMISSAO,T.DATASAIDA,
 F.DATAVENCIMENTO,T.VALORBRUTO,T.VALORLIQUIDO,F.VALORORIGINAL VALOR,
 CAST(F.STATUSLAN AS VARCHAR(10)) STATUS,F.VALORBAIXADO,F.BAIXAPENDENTE,F.IDBOLETO,
 (SELECT COUNT(*) FROM FLANBOLETO B WITH(READCOMMITTEDLOCK) WHERE B.CODCOLIGADA=F.CODCOLIGADA AND B.IDLAN=F.IDLAN) BOLETO_COUNT,
 F.IDPGTO,F.CODCOLPGTO,F.RECCREATEDON,F.RECMODIFIEDON,H.TICKET,
 CASE WHEN F.IDMOV IS NULL OR T.IDMOV IS NULL THEN 1 ELSE 0 END ORFAO
 FROM FLAN F WITH(READCOMMITTEDLOCK) CROSS JOIN P
 LEFT JOIN TMOV T WITH(READCOMMITTEDLOCK) ON T.CODCOLIGADA=F.CODCOLIGADA AND T.IDMOV=F.IDMOV
 LEFT JOIN TMOVCOMPL H WITH(READCOMMITTEDLOCK) ON H.CODCOLIGADA=F.CODCOLIGADA AND H.IDMOV=F.IDMOV
 WHERE F.CODCOLIGADA=P.COL AND (H.TICKET=P.TICKET OR
 (F.CODCOLCFO=P.CFOCOL AND F.CODCFO=P.CFO AND
 (LTRIM(RTRIM(LEFT(F.NUMERODOCUMENTO,CHARINDEX('/',F.NUMERODOCUMENTO+'/')-1)))=P.NUMERO
 OR TRY_CONVERT(BIGINT,LEFT(F.NUMERODOCUMENTO,CHARINDEX('/',F.NUMERODOCUMENTO+'/')-1))=TRY_CONVERT(BIGINT,P.NUMERO)
 OR (F.DATAEMISSAO>=P.EMISSAO AND F.DATAEMISSAO<DATEADD(DAY,1,P.EMISSAO))
 OR (F.RECCREATEDON>=P.INICIO AND F.RECCREATEDON<P.FIM))))
), R AS (SELECT * FROM M UNION ALL SELECT * FROM F)
SELECT TOP (1001) CAST(1 AS INT) OBS_VERSION,P.COL REQUEST_COMPANY,P.CFOCOL REQUEST_SUPPLIER_COMPANY,
 P.CFO REQUEST_SUPPLIER,P.TICKET REQUEST_TICKET,P.NUMERO REQUEST_NUMBER,P.EMISSAO REQUEST_ISSUE,
 P.INICIO REQUEST_START,P.FIM REQUEST_END,(SELECT COUNT(*) FROM M) TOTAL_MOVEMENTS,
 (SELECT COUNT(*) FROM F) TOTAL_LAUNCHES,R.*
FROM P LEFT JOIN R ON 1=1
ORDER BY R.ROW_KIND,R.CODCOLIGADA,R.IDMOV,R.IDLAN
