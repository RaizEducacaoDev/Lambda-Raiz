/* Complete current observation. Zero is NOT rollback evidence for CREATING.
   RESERVED/protocolVersion2 is separately fenced before any native dispatch. */
WITH P AS (
 SELECT CAST(:CODCOLIGADA AS INT) AS CODCOLIGADA, CAST(:TICKET AS VARCHAR(50)) AS TICKET
), M AS (
 SELECT T.CODCOLIGADA,T.IDMOV
 FROM dbo.TMOV T WITH(READCOMMITTEDLOCK)
 WHERE EXISTS(SELECT 1 FROM dbo.TMOVCOMPL H WITH(READCOMMITTEDLOCK), P
              WHERE H.CODCOLIGADA=T.CODCOLIGADA AND H.IDMOV=T.IDMOV AND H.TICKET=P.TICKET)
), F AS (
 SELECT F.CODCOLIGADA,F.IDMOV,F.IDLAN,
   (SELECT COUNT(*) FROM dbo.FLANBOLETO B WITH(READCOMMITTEDLOCK)
    WHERE B.CODCOLIGADA=F.CODCOLIGADA AND B.IDLAN=F.IDLAN) AS BOLETO_COUNT
 FROM dbo.FLAN F WITH(READCOMMITTEDLOCK)
 WHERE EXISTS(SELECT 1 FROM M WHERE M.CODCOLIGADA=F.CODCOLIGADA AND M.IDMOV=F.IDMOV)
), R AS (
 SELECT CAST('MOV' AS VARCHAR(8)) AS ROW_KIND,M.CODCOLIGADA,M.IDMOV,
        CAST(NULL AS INT) AS IDLAN,CAST(NULL AS INT) AS BOLETO_COUNT FROM M
 UNION ALL
 SELECT CAST('LAN' AS VARCHAR(8)),F.CODCOLIGADA,F.IDMOV,F.IDLAN,F.BOLETO_COUNT FROM F
)
SELECT CAST(1 AS INT) AS RETOMADA_VERSION,P.CODCOLIGADA AS REQUEST_COMPANY,P.TICKET AS REQUEST_TICKET,
 (SELECT COUNT(*) FROM M) AS TOTAL_MOVEMENTS,(SELECT COUNT(*) FROM F) AS TOTAL_LAUNCHES,
 COALESCE(R.ROW_KIND,'EMPTY') AS ROW_KIND,R.CODCOLIGADA,R.IDMOV,R.IDLAN,R.BOLETO_COUNT
FROM P LEFT JOIN R ON 1=1
ORDER BY R.ROW_KIND,R.CODCOLIGADA,R.IDMOV,R.IDLAN
