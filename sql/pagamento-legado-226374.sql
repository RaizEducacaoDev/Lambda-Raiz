WITH M AS (
 SELECT CAST('MOV' AS VARCHAR(8)) AS ROW_KIND,T.CODCOLIGADA,T.CODFILIAL,T.IDMOV,
   CAST(NULL AS INT) AS IDLAN,T.CODCOLCFO,T.CODCFO,T.NUMEROMOV AS DOCUMENTO,T.SERIE,T.CODTDO,
   T.DATAEMISSAO,T.RECCREATEDON,T.RECMODIFIEDON,T.VALORLIQUIDO AS VALOR,T.STATUS,
   CAST(NULL AS NUMERIC(18,4)) AS VALORBAIXADO,H.TICKET,CAST(0 AS INT) AS ORFAO,
   CASE WHEN H.TICKET='226374' THEN 1 ELSE 0 END AS TICKET_MATCH
 FROM dbo.TMOV T WITH(READCOMMITTEDLOCK)
 LEFT JOIN dbo.TMOVCOMPL H WITH(READCOMMITTEDLOCK) ON H.CODCOLIGADA=T.CODCOLIGADA AND H.IDMOV=T.IDMOV
 WHERE T.CODCOLIGADA=9 AND T.CODCOLCFO=0 AND T.CODCFO='0000154129'
  AND (TRY_CONVERT(BIGINT,T.NUMEROMOV) IN(114,1141) OR H.TICKET='226374'
       OR (T.DATAEMISSAO>='2026-10-22T00:00:00' AND T.DATAEMISSAO<'2026-10-23T00:00:00')
       OR (T.RECCREATEDON>='2026-11-02T11:38:00' AND T.RECCREATEDON<'2026-11-02T11:49:00')
       OR (T.RECCREATEDON>='2026-11-02T14:38:00' AND T.RECCREATEDON<'2026-11-02T14:49:00'))
), F AS (
 SELECT CAST('LAN' AS VARCHAR(8)) AS ROW_KIND,F.CODCOLIGADA,F.CODFILIAL,F.IDMOV,F.IDLAN,
   F.CODCOLCFO,F.CODCFO,F.NUMERODOCUMENTO AS DOCUMENTO,T.SERIE,T.CODTDO,
   F.DATAEMISSAO,F.RECCREATEDON,F.RECMODIFIEDON,F.VALORORIGINAL AS VALOR,
   CAST(F.STATUSLAN AS VARCHAR(10)) AS STATUS,F.VALORBAIXADO,H.TICKET,
   CASE WHEN F.IDMOV IS NULL OR T.IDMOV IS NULL THEN 1 ELSE 0 END AS ORFAO,
   CASE WHEN H.TICKET='226374' THEN 1 ELSE 0 END AS TICKET_MATCH
 FROM dbo.FLAN F WITH(READCOMMITTEDLOCK)
 LEFT JOIN dbo.TMOV T WITH(READCOMMITTEDLOCK) ON T.CODCOLIGADA=F.CODCOLIGADA AND T.IDMOV=F.IDMOV
 LEFT JOIN dbo.TMOVCOMPL H WITH(READCOMMITTEDLOCK) ON H.CODCOLIGADA=F.CODCOLIGADA AND H.IDMOV=F.IDMOV
 WHERE F.CODCOLIGADA=9 AND F.CODCOLCFO=0 AND F.CODCFO='0000154129'
  AND (TRY_CONVERT(BIGINT,LEFT(F.NUMERODOCUMENTO,CHARINDEX('/',F.NUMERODOCUMENTO+'/')-1)) IN(114,1141)
       OR H.TICKET='226374'
       OR (F.DATAEMISSAO>='2026-10-22T00:00:00' AND F.DATAEMISSAO<'2026-10-23T00:00:00')
       OR (F.RECCREATEDON>='2026-11-02T11:38:00' AND F.RECCREATEDON<'2026-11-02T11:49:00')
       OR (F.RECCREATEDON>='2026-11-02T14:38:00' AND F.RECCREATEDON<'2026-11-02T14:49:00'))
), R AS (SELECT * FROM M UNION ALL SELECT * FROM F)
SELECT CAST(1 AS INT) AS OBS_VERSION,(SELECT COUNT(*) FROM M) AS TOTAL_MOVEMENTS,
  (SELECT COUNT(*) FROM F) AS TOTAL_LAUNCHES,R.*
FROM (SELECT 1 AS SENTINEL) S LEFT JOIN R ON 1=1
ORDER BY R.ROW_KIND,R.CODCOLIGADA,R.CODFILIAL,R.IDMOV,R.IDLAN
