/* Read-only creation preflight, never permission to release CREATING.
   Mirrors the service-invoice header emitted by this integration: no CRO or
   SUBSERIE, supplier as issuer and the native financial document type.
   Complete echoed scope and counts; no TOP 1, secrets or bank information.
*/
WITH P AS (
 SELECT CAST(:CODCOLIGADA AS INT) AS CODCOLIGADA,
        CAST(:CODFILIAL AS INT) AS CODFILIAL,
        CAST(:CODCOLCFO AS INT) AS CODCOLCFO,
        CAST(:CODCFO AS VARCHAR(30)) AS CODCFO,
        CAST(:CODTMV AS VARCHAR(20)) AS CODTMV,
        CAST(:NUMERO AS VARCHAR(9)) AS NUMERO,
        CASE WHEN CAST(:SERIE AS VARCHAR(16)) = '~' THEN CAST('' AS VARCHAR(5)) ELSE CAST(:SERIE AS VARCHAR(5)) END AS SERIE
), CONFIG AS (
 SELECT P.*, T.MASCARANUMEROMOV, T.CODTDOLANDUP,
        CASE WHEN T.CODTMV IS NULL THEN 0 ELSE 1 END AS HAS_MOVEMENT_TYPE,
        (SELECT COUNT(*) FROM dbo.TTMVSERIE S WITH(NOLOCK)
          WHERE S.CODCOLIGADA=P.CODCOLIGADA AND S.CODTMV=P.CODTMV AND S.PRINCIPAL=1) AS PRINCIPAL_COUNT,
        (SELECT MIN(S.SERIE) FROM dbo.TTMVSERIE S WITH(NOLOCK)
          WHERE S.CODCOLIGADA=P.CODCOLIGADA AND S.CODTMV=P.CODTMV AND S.PRINCIPAL=1) AS PRINCIPAL_SERIES
 FROM P LEFT JOIN dbo.TTMV T WITH(NOLOCK)
  ON T.CODCOLIGADA=P.CODCOLIGADA AND T.CODTMV=P.CODTMV
), EFFECTIVE AS (
 SELECT C.*, CASE WHEN C.SERIE<>'' THEN C.SERIE
                  WHEN C.PRINCIPAL_COUNT=1 THEN C.PRINCIPAL_SERIES ELSE '' END AS EFFECTIVE_SERIES,
        CASE WHEN LEN(C.MASCARANUMEROMOV) BETWEEN 1 AND 9
                  AND REPLACE(C.MASCARANUMEROMOV,'#','')=''
                  AND LEN(C.NUMERO)<=LEN(C.MASCARANUMEROMOV)
             THEN RIGHT(REPLICATE('0',LEN(C.MASCARANUMEROMOV))+C.NUMERO,LEN(C.MASCARANUMEROMOV))
             ELSE '' END AS EFFECTIVE_NUMBER
 FROM CONFIG C
), MATCHES AS (
 SELECT M.CODCOLIGADA,M.IDMOV,M.CODFILIAL,M.CODCOLCFO,M.CODCFO,M.CODTMV,
        M.SERIE,M.NUMEROMOV,M.CODTDO,M.CODCOLCFOAUX,M.CODCFOAUX,M.CRO,M.SUBSERIE,H.TICKET
 FROM EFFECTIVE E INNER JOIN dbo.TMOV M WITH(NOLOCK)
  ON M.CODCOLIGADA=E.CODCOLIGADA AND M.CODFILIAL=E.CODFILIAL
  AND M.CODCOLCFOAUX=E.CODCOLCFO AND M.CODCFOAUX=E.CODCFO
  AND M.SERIE=E.EFFECTIVE_SERIES AND M.NUMEROMOV=E.EFFECTIVE_NUMBER
  AND M.CODTDO=E.CODTDOLANDUP AND M.CRO IS NULL AND M.SUBSERIE IS NULL
 LEFT JOIN dbo.TMOVCOMPL H WITH(NOLOCK) ON H.CODCOLIGADA=M.CODCOLIGADA AND H.IDMOV=M.IDMOV
 WHERE E.EFFECTIVE_SERIES<>'' AND E.EFFECTIVE_NUMBER<>''
)
SELECT CAST(1 AS INT) AS DOC_VERSION,
 E.CODCOLIGADA AS REQUEST_COMPANY,E.CODFILIAL AS REQUEST_BRANCH,
 E.CODCOLCFO AS REQUEST_SUPPLIER_COMPANY,E.CODCFO AS REQUEST_SUPPLIER,
 E.CODTMV AS REQUEST_MOVEMENT_TYPE,E.NUMERO AS REQUEST_NUMBER,E.SERIE AS REQUEST_SERIES,
 E.HAS_MOVEMENT_TYPE,E.MASCARANUMEROMOV AS MASK,E.PRINCIPAL_COUNT,
 E.EFFECTIVE_SERIES,E.EFFECTIVE_NUMBER,E.CODTDOLANDUP AS EFFECTIVE_DOCUMENT_TYPE,
 (SELECT COUNT(*) FROM dbo.TTMVSERIE S WITH(NOLOCK)
   WHERE S.CODCOLIGADA=E.CODCOLIGADA AND S.CODTMV=E.CODTMV AND S.SERIE=E.EFFECTIVE_SERIES) AS SERIES_MATCH_COUNT,
 COUNT(M.IDMOV) OVER() AS DOC_MATCH_COUNT,
 M.CODCOLIGADA,M.IDMOV,M.CODFILIAL,M.CODCOLCFO,M.CODCFO,M.CODTMV,
 M.SERIE,M.NUMEROMOV,M.CODTDO,M.CODCOLCFOAUX,M.CODCFOAUX,M.CRO,M.SUBSERIE,M.TICKET
FROM EFFECTIVE E LEFT JOIN MATCHES M ON 1=1
ORDER BY M.IDMOV
