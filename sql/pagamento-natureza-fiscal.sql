/* RAIZ.PG.FISC/0/T - read-only preflight, no fiscal substitution or personal data. */
WITH P AS (
 SELECT CAST(:CODCOLIGADA AS INT) AS CODCOLIGADA,
        CAST(:CODFILIAL AS INT) AS CODFILIAL,
        CAST(:CODCOLCFO AS INT) AS CODCOLCFO,
        CAST(:CODCFO AS VARCHAR(30)) AS CODCFO,
        CAST(:IDNAT AS INT) AS IDNAT
)
SELECT CAST(1 AS INT) AS FISCAL_VERSION,
 P.CODCOLIGADA AS REQUEST_COMPANY,P.CODFILIAL AS REQUEST_BRANCH,
 P.CODCOLCFO AS REQUEST_SUPPLIER_COMPANY,P.CODCFO AS REQUEST_SUPPLIER,
 P.IDNAT AS REQUEST_NATURE,
 CASE WHEN C.CODCFO IS NOT NULL THEN 1 ELSE 0 END AS HAS_SUPPLIER,
 CASE WHEN F.CODFILIAL IS NOT NULL THEN 1 ELSE 0 END AS HAS_BRANCH,
 CASE WHEN N.IDNAT IS NOT NULL THEN 1 ELSE 0 END AS HAS_NATURE,
 N.CODCOLIGADA AS NATURE_COMPANY,N.IDNAT AS NATURE_ID,N.CODNAT AS NATURE_CODE,
 N.ATIVO AS NATURE_ACTIVE,N.ORIGEMDESTINO AS NATURE_ROUTE,
 C.CODETD AS SUPPLIER_UF,C.IDPAIS AS SUPPLIER_COUNTRY_ID,
 F.ESTADO AS BRANCH_UF,F.IDPAIS AS BRANCH_COUNTRY_ID
FROM P
LEFT JOIN dbo.FCFO C WITH(NOLOCK) ON C.CODCOLIGADA=P.CODCOLCFO AND C.CODCFO=P.CODCFO
LEFT JOIN dbo.GFILIAL F WITH(NOLOCK) ON F.CODCOLIGADA=P.CODCOLIGADA AND F.CODFILIAL=P.CODFILIAL
LEFT JOIN dbo.DNATUREZA N WITH(NOLOCK) ON N.CODCOLIGADA=P.CODCOLIGADA AND N.IDNAT=P.IDNAT
