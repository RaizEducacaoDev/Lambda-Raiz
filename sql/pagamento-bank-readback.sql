/* RAIZ.PG.BANK2: committed, read-only snapshot of eight exact existing chains.
   Full records stay in the operator's memory; artifacts contain IDs and hashes.
   No dynamic SQL, mutation, provider/name search or permission to create. */
WITH P AS (
 SELECT CAST(:CODCOLIGADA AS INT) AS CODCOLIGADA,
        CAST(:TICKET AS INT) AS TICKET,
        CAST(:IDMOV AS INT) AS IDMOV,
        CAST(:IDLAN AS INT) AS IDLAN
), ALLOWLIST AS (
 SELECT V.CODCOLIGADA,V.TICKET,V.IDMOV,V.IDLAN
 FROM (VALUES
   (5,228007,165611,634500),
   (18,227386,407685,2191110),
   (25,226610,42677,79094),
   (8,228103,565011,870364),
   (8,228158,565012,870365),
   (8,228198,565013,870366),
   (8,228275,565014,870367),
   (2,228793,278473,751379)
 ) V(CODCOLIGADA,TICKET,IDMOV,IDLAN)
), S AS (
 SELECT P.*, CASE WHEN A.TICKET IS NULL THEN 0 ELSE 1 END AS ALLOWED
 FROM P LEFT JOIN ALLOWLIST A
 ON A.CODCOLIGADA=P.CODCOLIGADA AND A.TICKET=P.TICKET
 AND A.IDMOV=P.IDMOV AND A.IDLAN=P.IDLAN
)
SELECT CAST(1 AS INT) AS BANK_VERSION,
 S.CODCOLIGADA AS REQUEST_COMPANY,S.TICKET AS REQUEST_TICKET,
 S.IDMOV AS REQUEST_IDMOV,S.IDLAN AS REQUEST_IDLAN,S.ALLOWED AS EXACT_SCOPE_ALLOWED,
 (SELECT M.* FROM dbo.TMOV M WITH(READCOMMITTEDLOCK)
  WHERE S.ALLOWED=1 AND M.CODCOLIGADA=S.CODCOLIGADA AND M.IDMOV=S.IDMOV
  FOR JSON PATH,INCLUDE_NULL_VALUES) AS MOVEMENT_JSON,
 (SELECT L.* FROM dbo.FLAN L WITH(READCOMMITTEDLOCK)
  WHERE S.ALLOWED=1 AND L.CODCOLIGADA=S.CODCOLIGADA AND L.IDMOV=S.IDMOV
  ORDER BY L.IDLAN FOR JSON PATH,INCLUDE_NULL_VALUES) AS LAUNCH_JSON,
 (SELECT M.CODCOLIGADA,M.IDMOV FROM dbo.TMOV M WITH(READCOMMITTEDLOCK)
  INNER JOIN dbo.TMOVCOMPL H WITH(READCOMMITTEDLOCK)
  ON H.CODCOLIGADA=M.CODCOLIGADA AND H.IDMOV=M.IDMOV
  WHERE S.ALLOWED=1 AND H.TICKET=CONVERT(VARCHAR(50),S.TICKET)
  ORDER BY M.CODCOLIGADA,M.IDMOV FOR JSON PATH,INCLUDE_NULL_VALUES) AS OWNED_MOVEMENTS_JSON,
 (SELECT L.CODCOLIGADA,L.IDLAN FROM dbo.FLAN L WITH(READCOMMITTEDLOCK)
  INNER JOIN dbo.TMOVCOMPL H WITH(READCOMMITTEDLOCK)
  ON H.CODCOLIGADA=L.CODCOLIGADA AND H.IDMOV=L.IDMOV
  WHERE S.ALLOWED=1 AND H.TICKET=CONVERT(VARCHAR(50),S.TICKET)
  ORDER BY L.CODCOLIGADA,L.IDLAN FOR JSON PATH,INCLUDE_NULL_VALUES) AS OWNED_LAUNCHES_JSON,
 (SELECT H.TICKET FROM dbo.TMOVCOMPL H WITH(READCOMMITTEDLOCK)
  WHERE S.ALLOWED=1 AND H.CODCOLIGADA=S.CODCOLIGADA AND H.IDMOV=S.IDMOV
  FOR JSON PATH,INCLUDE_NULL_VALUES) AS COMPLEMENT_JSON,
 (SELECT COUNT(*) FROM dbo.FLANBOLETO B WITH(READCOMMITTEDLOCK)
  WHERE S.ALLOWED=1 AND B.CODCOLIGADA=S.CODCOLIGADA AND B.IDLAN=S.IDLAN) AS BOLETO_COUNT,
 (SELECT COUNT(*) FROM dbo.FLANBAIXA B WITH(READCOMMITTEDLOCK)
  WHERE S.ALLOWED=1 AND B.CODCOLIGADA=S.CODCOLIGADA AND B.IDLAN=S.IDLAN) AS PAYMENT_COUNT
FROM S
