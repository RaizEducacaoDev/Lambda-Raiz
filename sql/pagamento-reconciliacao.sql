/* Draft contract: complete movement identities, not permission to create/retry. */
WITH MOVIMENTOS AS (
 SELECT T.CODCOLIGADA,T.IDMOV,T.CODFILIAL,T.CODCFO,T.CODCOLCFO,T.CODTMV,T.STATUS,H.TICKET
 FROM dbo.TMOV T WITH(NOLOCK)
 INNER JOIN dbo.TMOVCOMPL H WITH(NOLOCK)
  ON H.CODCOLIGADA=T.CODCOLIGADA AND H.IDMOV=T.IDMOV
 WHERE T.CODCOLIGADA=:CODCOLIGADA AND H.TICKET=:TICKET
)
SELECT CAST(1 AS INT) AS RECON_VERSION,
 CAST(:CODCOLIGADA AS INT) AS REQUEST_COMPANY,
 CAST(:TICKET AS VARCHAR(50)) AS REQUEST_TICKET,
 COUNT(M.IDMOV) OVER() AS TOTAL_MOVEMENTS,
 M.CODCOLIGADA,M.IDMOV,M.CODFILIAL,M.CODCFO,M.CODCOLCFO,M.CODTMV,M.STATUS,M.TICKET
FROM (SELECT 1 AS SENTINEL) S
LEFT JOIN MOVIMENTOS M ON 1=1
ORDER BY M.IDMOV
